import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

const source = readFileSync(new URL('../../src/js/mapview-iso.js', import.meta.url), 'utf8');
const context = { console, performance: { now: () => 100 }, window: {}, Farm: { state: { data: { map: [{ gx: 2, gy: 3 }] }, save() { saves++; } } } };
context.window = context;
vm.createContext(context);
vm.runInContext(source, context);
const iso = context.Farm.isoView;
let actions = 0, saves = 0, glides = 0;
iso.render = () => {};
iso._glideStop = () => {};
iso._glideStart = () => { glides++; };
iso._plotAtPoint = () => ({ i: 0, gx: 1, gy: 1 });
iso._visitPlotTap = () => { actions++; };
iso._commitPlace = () => { actions++; };
const route = source.match(/addEventListener\('pointercancel', \(e\) => this\.(\w+)\(e\)\)/)[1];
const cancel = () => iso[route]({ pointerId: 1 });
const prime = () => {
  iso._pointers = { 1: { x: 10, y: 10 } };
  iso._drag = { moved: false, x: 10, y: 10 };
  iso._pressCell = { gx: 1, gy: 1 };
  iso._pressBuilding = 0;
  iso._moving = iso._pinch = null;
  iso._placing = iso._painting = iso._visit = false;
};

prime(); iso._visit = true; cancel();
assert.equal(actions, 0, 'cancelled tap must not harvest, water, or open a building');
prime(); iso._placing = { type: 'home' }; iso._placeDown = true; cancel();
assert.equal(actions, 0, 'cancelled placement must not buy or commit');
prime(); iso._moving = { kind: 'building', idx: 0, gx: 8, gy: 8, moved: true, valid: true }; cancel();
assert.equal(saves, 0, 'cancelled move must retain the saved position');
assert.equal(context.Farm.state.data.map[0].gx, 2);
prime(); iso._drag.moved = true; cancel();
assert.equal(glides, 0, 'cancel must not launch inertia');
assert.equal(Object.keys(iso._pointers).length, 0);
assert.equal(iso._drag, null);
assert.equal(iso._pressCell, null);
assert.equal(iso._pressBuilding, -1);
prime(); iso._pointers[2] = { x: 15, y: 15 }; iso._pinch = { dist: 4 }; cancel();
assert.equal(Object.keys(iso._pointers).length, 0, 'cancelled pinch must not leave a second finger armed');
prime(); iso._pointers = {}; iso._placing = { type: 'home' };
iso._cv = { setPointerCapture() {} };
iso._local = e => ({ x: e.clientX, y: e.clientY });
iso._updatePlace = () => {};
iso._down({ pointerId: 1, clientX: 10, clientY: 10 });
iso._down({ pointerId: 2, clientX: 30, clientY: 30 });
iso._up({ pointerId: 1 }); iso._up({ pointerId: 2 });
assert.equal(actions, 0, 'a placement pinch must not become a purchase when the last finger lifts');
console.log('ok farm-premium pointer cancellation (tap, placement, move, inertia, pinch)');
